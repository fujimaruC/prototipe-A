import { chromium, devices } from 'playwright';
const B = 'http://localhost:4400/prototipe-A/';
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const d = await b.newPage({ viewport: { width: 1394, height: 723 } });
await d.goto(B + '?quality=high', { waitUntil: 'networkidle' });
await d.waitForTimeout(3400);
await d.screenshot({ path: '.shots-p2/g-final-desktop.png' });
await d.close();
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const m = await ctx.newPage();
await m.goto(B, { waitUntil: 'networkidle' });
await m.waitForTimeout(2800);
await m.screenshot({ path: '.shots-p2/g-final-mobile.png' });
await ctx.close();
await b.close();
console.log('ok');
