import { chromium, devices } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const p = await ctx.newPage();
await p.goto('http://localhost:4400/prototipe-A/', { waitUntil: 'networkidle' });
await p.waitForTimeout(2600);
const box = await p.locator('.fuji').boundingBox();
const frame = () => p.evaluate(() => document.querySelector('.fuji')?.getAttribute('data-frame'));
await p.tap('.fuji');
await p.waitForTimeout(150);
const afterTap = await frame();
await p.waitForTimeout(1000);
await p.tap('.fuji');
await p.waitForTimeout(90);
await p.tap('.fuji');
await p.waitForTimeout(150);
const afterDouble = await frame();
await p.screenshot({ path: '.shots-p2/tap-mobile.png' });
console.log(JSON.stringify({ box: box ? { w: Math.round(box.width), h: Math.round(box.height) } : null, afterTap, afterDouble }));
await b.close();
