import { chromium } from 'playwright';
const B = 'http://127.0.0.1:5173';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto(B + '/', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
await p.screenshot({ path: '.shots/live-hero.png' });
await p.evaluate(() => document.getElementById('cases').scrollIntoView());
await p.waitForTimeout(600);
await p.locator('.row').first().locator('.summary').click();
await p.waitForTimeout(700);
await p.screenshot({ path: '.shots/live-cases.png' });
await p.keyboard.press('/');
await p.waitForTimeout(400);
await p.screenshot({ path: '.shots/live-index.png' });
await p.keyboard.press('Escape');
await p.waitForTimeout(300);
await p.getByRole('button', { name: /Positive/ }).click();
await p.waitForTimeout(600);
await p.evaluate(() => window.scrollTo(0, 0));
await p.waitForTimeout(300);
await p.screenshot({ path: '.shots/live-negative.png' });
const ph = await b.newPage({ viewport: { width: 390, height: 844 } });
await ph.goto(B + '/', { waitUntil: 'networkidle' });
await ph.waitForTimeout(900);
await ph.screenshot({ path: '.shots/live-phone.png' });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
console.log('console/page errors:', errs.length, errs.slice(0, 3));
await b.close();
