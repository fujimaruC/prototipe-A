export type SpriteFrame = 'idle' | 'blink' | 'walk' | 'wave' | 'love';

export const FRAMES: Record<SpriteFrame, string[]> = { idle: IDLE, blink: BLINK, walk: WALK, wave: WAVE, love: LOVE };

/** Guards the art: every frame must be 24 rows of exactly 24 cells. */
for (const [name, rows] of Object.entries(FRAMES)) {
	if (rows.length !== 24) throw new Error(`sprite ${name}: ${rows.length} rows`);
	rows.forEach((r, i) => {
		if (r.length !== 24) throw new Error(`sprite ${name} row ${i}: ${r.length} cells`);
	});
}
